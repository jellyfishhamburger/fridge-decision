const assert = require('node:assert/strict');
const {create,remaining,apply} = require('../pebble-state.js');
const original = create('session-1',{id:'demo',steps:[{text:'A',seconds:30},{text:'B',seconds:60}]},1000);
const command = (s,action,extra={})=>({session_id:s.id,revision:s.revision,action,...extra});
let s=apply(original,command(original,'toggle_timer'),1000);
assert.equal(remaining(s,6000),25000);
const firstPress=command(original,'toggle_timer');
assert.throws(()=>apply(s,firstPress,6000),/Stale/);
s=apply(s,command(s,'toggle_timer'),6000);
assert.equal(remaining(s,12000),25000);
s=apply(s,command(s,'toggle_timer'),12000);
assert.equal(remaining(s,15000),22000);
s=apply(s,command(s,'set_step',{step_index:1}),15000);
assert.equal(s.timer_ends_at,null); assert.equal(s.remaining_ms,60000);
assert.throws(()=>apply(s,command(s,'set_step',{step_index:2})),/Invalid/);
assert.throws(()=>apply(s,{...command(s,'exit'),session_id:'old-session'}),/Wrong/);
s=apply(s,command(s,'exit'),16000);
assert.equal(s.status,'exited'); assert.equal(remaining(s,20000),0);
assert.throws(()=>apply(s,command(s,'toggle_timer')),/ended/);
assert.equal(original.revision,0); assert.equal(original.timer_ends_at,null);
let expired=apply(original,command(original,'toggle_timer'),1000);
assert.equal(remaining(expired,999999),0);
expired=apply(expired,command(expired,'toggle_timer'),999999);
assert.equal(expired.timer_ends_at,null);
assert.throws(()=>create('x',{steps:[{text:'bad',seconds:-1}]}),/Invalid/);
console.log('PASS: timer pause/resume, step bounds/reset, exit, stale retries, session isolation, expiry and immutable input');

import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {makeFrameHandler} from '../supabase/functions/fridge-frame/handler.mjs';
import {inventoryRows,renderFrame,renderPages} from '../supabase/functions/fridge-frame/render.mjs';
const id='11111111-1111-4111-8111-111111111111',secret='a'.repeat(64),now=Date.parse('2026-11-07T08:05:00Z');let calls=0;
const items=[{name:'鸡蛋',qty:2,life:2,added_at:'2026-11-05'},{name:'牛奶',qty:1,days_left:3}];
const store={async device(){return {household_id:'home',secret_hash:createHash('sha256').update(secret).digest('hex')};},async inventory(home){assert.equal(home,'home');calls++;return items;}};
const handler=makeFrameHandler({store,now:()=>now});
const req=(token=secret,etag)=>new Request(`https://example.test/fridge-frame?device_id=${id}&household_id=other`,{headers:{'x-device-secret':token,...(etag?{'if-none-match':etag}:{})}});
assert.equal((await handler(req('b'.repeat(64)))).status,401);assert.equal(calls,0);
const r=await handler(req());assert.equal(r.status,200);const bytes=new Uint8Array(await r.arrayBuffer());assert.equal(r.headers.get('x-frame-pages'),'3');assert.equal(bytes.length,45000);assert(bytes.some(Boolean));
assert.equal(createHash('sha256').update(bytes).digest('hex'),r.headers.get('x-frame-sha256'));
assert.equal((await handler(req(secret,r.headers.get('etag')))).status,304);
assert.equal(inventoryRows(items,now)[0].days,0);
assert.equal(inventoryRows([{name:'过期',qty:1,life:1,added_at:'2026-11-05'}],now)[0].days,-1);
assert.deepEqual(renderFrame(items,now),renderFrame(items,now+60000));
assert.notDeepEqual(renderFrame(items,now),renderFrame([],now));
store.inventory=async()=>{throw Error('db');};assert.equal((await handler(req())).status,503);
assert.equal(renderPages(items,now).length,3);
console.log('PASS frame auth/household isolation, 3-page 45000-byte format, SHA256/304, stable refresh window, expiry and failed-fetch preservation contract');

"""Generate offline 400x300 one-bit firmware pages. No network or real inventory."""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont
p=argparse.ArgumentParser()
p.add_argument('--font',default='C:/Windows/Fonts/msyh.ttc')
a=p.parse_args()
root=Path(__file__).resolve().parents[2]
out=root/'firmware'/'FridgeDemo'
preview=Path(__file__).resolve().parent/'preview'
preview.mkdir(exist_ok=True)
fonts={n:ImageFont.truetype(a.font,n) for n in (16,20,24,30,36)}
pages=[('先吃这些',[('鸡蛋','还剩 1 天'),('菠菜','还剩 2 天'),('牛奶','还剩 3 天')]),('今晚吃什么',[('菠菜鸡蛋面','约 15 分钟'),('优先使用临期食材','鸡蛋 · 菠菜'),('按操作键查看步骤','仅演示，不扣库存')]),('设备状态',[('屏幕：Z96 配置','实体屏已点亮'),('按键：上拉输入','GPIO 4 / 5 / 13'),('数据：离线演示','尚未连接真实库存')]),('菠菜鸡蛋面',[('1  煮面','按包装时间煮熟'),('2  加菠菜、鸡蛋','继续煮至充分熟透'),('3  盛出调味','演示步骤，不记录做饭')])]
lines=['// Generated by tools/fridge_demo/generate.py; bit 1 = black.','#pragma once','#include <Arduino.h>']
for i,(title,rows) in enumerate(pages):
    im=Image.new('1',(400,300),1);d=ImageDraw.Draw(im)
    d.rectangle((0,0,399,299),outline=0)
    d.rectangle((0,0,399,29),fill=0)
    d.text((12,3),'FRIDGE DECISION · 演示数据',font=fonts[16],fill=1)
    d.text((14,37),title,font=fonts[36],fill=0)
    for y,(left,right) in zip((94,147,200),rows):
        d.text((16,y),left,font=fonts[24],fill=0)
        d.text((16,y+29),right,font=fonts[16],fill=0)
    d.line((12,253,387,253),fill=0)
    d.text((14,259),'4 上页   5 下页   13 操作',font=fonts[20],fill=0)
    d.text((14,284),'数字为 GPIO；翻页需等待，按键不扣库存',font=fonts[16],fill=0)
    # Last row must stay within screen; use compact footer instead.
    d.rectangle((1,281,398,298),fill=1)
    d.text((14,281),'离线演示 · 翻页有等待 · 不修改库存',font=fonts[16],fill=0)
    im.save(preview/f'page-{i}.png')
    data=[]
    for y in range(300):
        for x in range(0,400,8):
            data.append(sum((1 if im.getpixel((x+b,y))==0 else 0)<<(7-b) for b in range(8)))
    assert len(data)==15000
    lines.append(f'const uint8_t PAGE_{i}[15000] PROGMEM = {{')
    lines.extend(','.join(f'0x{v:02x}' for v in data[j:j+50])+',' for j in range(0,len(data),50))
    lines.append('};')
lines.append('const uint8_t* const PAGES[]={PAGE_0,PAGE_1,PAGE_2,PAGE_3};')
(out/'DemoPages.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated 4 pages, 15000 bytes each')
